-- Check total rows
SELECT COUNT(*) as total_sessions FROM game_sessions;

-- Check group distribution
SELECT test_group, COUNT(*) as count FROM game_sessions GROUP BY test_group;

-- Q4 Preview: Session length by group
SELECT
    test_group,
    COUNT(*) as sessions,
    ROUND(AVG(session_length_minutes), 2) as avg_session_length,
    ROUND(MIN(session_length_minutes), 2) as min_length,
    ROUND(MAX(session_length_minutes), 2) as max_length
FROM game_sessions
GROUP BY test_group;

-- Q5 Preview: Level 20 completion by group
SELECT
    test_group,
    COUNT(*) as total_attempts,
    SUM(level_20_completed) as completions,
    COUNT(*) - SUM(level_20_completed) as failures,
    ROUND(SUM(level_20_completed) * 100.0 / COUNT(*), 1) as completion_rate
FROM game_sessions
GROUP BY test_group;
